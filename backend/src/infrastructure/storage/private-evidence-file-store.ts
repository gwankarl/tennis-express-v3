import { createHash, randomUUID } from 'node:crypto';
import { createReadStream, createWriteStream } from 'node:fs';
import { mkdir, readdir, rename, rm, stat, unlink, utimes } from 'node:fs/promises';
import { join } from 'node:path';
import { Transform, type Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';

export const MAX_EVIDENCE_FILE_BYTES = 10 * 1024 * 1024;
export const ALLOWED_EVIDENCE_MEDIA_TYPES = ['image/jpeg', 'image/png', 'application/pdf'] as const;

export type EvidenceMediaType = (typeof ALLOWED_EVIDENCE_MEDIA_TYPES)[number];

export interface StagedEvidenceUpload {
  stageId: string;
  storageKey: string;
  mediaType: EvidenceMediaType;
  byteSize: number;
  sha256: string;
}

export class EvidenceUploadTooLargeError extends Error {
  constructor() {
    super('Evidence file exceeds the allowed size.');
    this.name = 'EvidenceUploadTooLargeError';
  }
}

export class UnsupportedEvidenceFileError extends Error {
  constructor() {
    super('Evidence file type is not supported.');
    this.name = 'UnsupportedEvidenceFileError';
  }
}

/**
 * Stores evidence outside web-served directories. Keys are generated by this
 * adapter; callers must not substitute a client filename or path.
 */
export class PrivateEvidenceFileStore {
  private readonly stagingDirectory: string;
  private readonly objectsDirectory: string;

  constructor(private readonly rootDirectory: string) {
    this.stagingDirectory = join(rootDirectory, '.staging');
    this.objectsDirectory = join(rootDirectory, 'objects');
  }

  async initialize(): Promise<void> {
    await mkdir(this.stagingDirectory, { recursive: true, mode: 0o700 });
    await mkdir(this.objectsDirectory, { recursive: true, mode: 0o700 });
  }

  /**
   * Streams one file into staging, enforcing the byte limit and validating the
   * detected media type before returning an opaque key.
   */
  async stage(source: Readable, declaredMediaType: string): Promise<StagedEvidenceUpload> {
    await this.initialize();

    const stageId = randomUUID();
    const storageKey = randomUUID();
    const stagePath = this.stagePath(stageId);
    const hash = createHash('sha256');
    const prefixChunks: Buffer[] = [];
    let prefixBytes = 0;
    let byteSize = 0;

    const meter = new Transform({
      transform(chunk: Buffer | Uint8Array, _encoding, callback) {
        const bytes = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk);
        byteSize += bytes.byteLength;

        if (byteSize > MAX_EVIDENCE_FILE_BYTES) {
          callback(new EvidenceUploadTooLargeError());
          return;
        }

        hash.update(bytes);

        const remainingPrefixBytes = 8192 - prefixBytes;
        if (remainingPrefixBytes > 0) {
          const prefix = bytes.subarray(0, remainingPrefixBytes);
          prefixChunks.push(prefix);
          prefixBytes += prefix.byteLength;
        }

        callback(null, bytes);
      },
    });

    try {
      await pipeline(source, meter, createWriteStream(stagePath, { flags: 'wx', mode: 0o600 }));

      const prefix = Buffer.concat(prefixChunks);
      const { fileTypeFromBuffer } = await import('file-type');
      const detected = await fileTypeFromBuffer(prefix);
      const normalizedDeclaredType = declaredMediaType.split(';', 1)[0]?.trim().toLowerCase();
      const mediaType = detected?.mime;

      if (
        !mediaType ||
        !ALLOWED_EVIDENCE_MEDIA_TYPES.includes(mediaType as EvidenceMediaType) ||
        mediaType !== normalizedDeclaredType
      ) {
        throw new UnsupportedEvidenceFileError();
      }

      if (byteSize === 0) {
        throw new UnsupportedEvidenceFileError();
      }

      return {
        stageId,
        storageKey,
        mediaType: mediaType as EvidenceMediaType,
        byteSize,
        sha256: hash.digest('hex'),
      };
    } catch (error) {
      await rm(stagePath, { force: true });
      throw error;
    }
  }

  /** Atomically moves a completed staging file into private object storage. */
  async promote(staged: StagedEvidenceUpload): Promise<void> {
    this.assertUuid(staged.stageId);
    this.assertUuid(staged.storageKey);
    await this.initialize();
    await rename(this.stagePath(staged.stageId), this.objectPath(staged.storageKey));
  }

  /** Removes a staging file after a failed upload or failed metadata commit. */
  async discardStaged(staged: StagedEvidenceUpload): Promise<void> {
    this.assertUuid(staged.stageId);
    await rm(this.stagePath(staged.stageId), { force: true });
  }

  /** Opens a private object for a route that has already authorized retrieval. */
  openStored(storageKey: string): Readable {
    this.assertUuid(storageKey);
    return createReadStream(this.objectPath(storageKey));
  }

  /** Removes one superseded or unreferenced private object. */
  async deleteStored(storageKey: string): Promise<void> {
    this.assertUuid(storageKey);

    try {
      await unlink(this.objectPath(storageKey));
    } catch (error) {
      if (!isMissingFile(error)) {
        throw error;
      }
    }
  }

  /**
   * Removes abandoned staging files older than the grace period. Call this at
   * startup and periodically; the default keeps recent in-flight files safe.
   */
  async cleanupAbandonedStaging(
    olderThanMs = 24 * 60 * 60 * 1000,
    now = Date.now(),
  ): Promise<number> {
    await this.initialize();
    const entries = await readdir(this.stagingDirectory, { withFileTypes: true });
    let removed = 0;

    for (const entry of entries) {
      if (!entry.isFile() || !/^[0-9a-f-]{36}\.part$/iu.test(entry.name)) {
        continue;
      }

      const path = join(this.stagingDirectory, entry.name);
      const file = await stat(path);

      if (file.mtimeMs <= now - olderThanMs) {
        await rm(path, { force: true });
        removed += 1;
      }
    }

    return removed;
  }

  /**
   * Removes old objects not referenced by current metadata. This cleans up
   * files left behind by a crash between promotion and a metadata transaction,
   * and superseded objects whose immediate deletion failed.
   */
  async cleanupOrphanedObjects(
    referencedStorageKeys: ReadonlySet<string>,
    olderThanMs = 24 * 60 * 60 * 1000,
    now = Date.now(),
  ): Promise<number> {
    await this.initialize();
    const entries = await readdir(this.objectsDirectory, { withFileTypes: true });
    let removed = 0;

    for (const entry of entries) {
      const match = /^([0-9a-f-]{36})\.blob$/iu.exec(entry.name);
      if (!entry.isFile() || !match?.[1] || referencedStorageKeys.has(match[1])) {
        continue;
      }

      const path = join(this.objectsDirectory, entry.name);
      const file = await stat(path);

      if (file.mtimeMs <= now - olderThanMs) {
        await rm(path, { force: true });
        removed += 1;
      }
    }

    return removed;
  }

  /** Test helper for aging a private file without waiting for the grace period. */
  async setModifiedTimeForCleanup(
    kind: 'staging' | 'object',
    key: string,
    modifiedAt: Date,
  ): Promise<void> {
    this.assertUuid(key);
    const path = kind === 'staging' ? this.stagePath(key) : this.objectPath(key);
    await utimes(path, modifiedAt, modifiedAt);
  }

  private stagePath(stageId: string): string {
    return join(this.stagingDirectory, `${stageId}.part`);
  }

  private objectPath(storageKey: string): string {
    return join(this.objectsDirectory, `${storageKey}.blob`);
  }

  private assertUuid(value: string): void {
    if (
      !/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/iu.test(value)
    ) {
      throw new Error('Invalid private storage key.');
    }
  }
}

function isMissingFile(error: unknown): boolean {
  return typeof error === 'object' && error !== null && 'code' in error && error.code === 'ENOENT';
}
